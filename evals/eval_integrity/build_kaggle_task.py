"""Build the Kaggle Benchmarks task file from the same taxonomy, prompt, parser and scorer as the Inspect task.

Kaggle runs a task file on its own, so this writes one self-contained script: the three modules' source, then the
public cards as JSON, then the task. Run it again whenever the cards or scoring change; a test checks the file in the
repo is up to date.

    python -m evals.eval_integrity.build_kaggle_task [--limit N --out PATH]
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from evals.eval_integrity.cards import fingerprint, load

HERE = Path(__file__).parent
OUT = HERE / "kaggle_task.py"
MODULES = ("taxonomy.py", "prompt.py", "scoring.py")
TASK_NAME = "Is this eval lying?"

TASK = '''
# %%
import random

import kaggle_benchmarks as kbench
import pandas as pd

CARDS_SHA256 = "{sha}"
CASES = json.loads({cases!r})
# Kaggle reserves quota against the maximum possible output, so an uncapped call can be refused before it starts.
# The answer is a short JSON object. 8,000 tokens was too tight for GLM-5, which spent it all thinking on 9 clean
# cards and never answered; no other model used more than about 5,000. 32,000 leaves room for long reasoning.
MAX_OUTPUT_TOKENS = 32000


@kbench.task(name="eval-integrity-card", store_task=False)
def audit_card(llm, case_json: str) -> dict:
    case = json.loads(case_json)
    reply = llm.prompt(build(case["text"]), extra_api_params={{"max_tokens": MAX_OUTPUT_TOKENS}})
    return score_case(case, parse(str(reply)))


def _pair_interval(rows: list[dict], draws: int = 2000) -> float:
    """Half-width of a bootstrap 95% interval for pair accuracy, resampling pairs."""
    pairs: dict = {{}}
    for r in rows:
        if r["pair"]:
            pairs.setdefault(r["pair"], []).append(r["correct"])
    wins = [len(v) == 2 and all(v) for v in pairs.values()]
    rng = random.Random(20261001)
    means = sorted(sum(rng.choice(wins) for _ in wins) / len(wins) for _ in range(draws))
    return round((means[int(0.975 * draws)] - means[int(0.025 * draws)]) / 2, 4)


@kbench.task(name="{name}", description="Can a model tell when an evaluation is misleading? Matched pairs of "
             "flawed and clean evaluation write-ups, plus decoys. Score: pair accuracy (both twins right, with the "
             "flaw named), with a bootstrap 95% interval.")
def eval_integrity(llm) -> tuple[float, float]:
    data = pd.DataFrame({{"case_json": [json.dumps(c) for c in CASES]}})
    with kbench.client.enable_cache():
        runs = audit_card.evaluate(llm=[llm], evaluation_data=data, n_jobs=2, timeout=600, max_attempts=3,
                                   retry_delay=20, on_failure="continue")
    completed = runs.completed_runs
    rows = list(completed.as_dataframe().result) if len(completed) else []
    done = {{r["id"] for r in rows}}
    rows += [score_case(c, {{}}) for c in CASES if c["id"] not in done]     # a failed call counts as wrong
    summary = summarise(rows)
    print(json.dumps({{"cards_sha256": CARDS_SHA256, "errored_calls": len(CASES) - len(done), **summary}}, indent=1))
    kbench.assertions.assert_true(summary["unparsed"] <= 0.1,
                                  expectation="At least 90% of answers are readable JSON with a verdict")
    return float(summary["pair_accuracy"]), _pair_interval(rows)


eval_integrity.run(kbench.llm)
'''


def module_source(name: str) -> str:
    src = (HERE / name).read_text(encoding="utf-8")
    src = re.sub(r"^from __future__ import annotations\n", "", src, flags=re.M)
    src = re.sub(r"^from \.\w+ import .*\n", "", src, flags=re.M)
    return f"# %%\n# ---- {name} ----\n{src.strip()}\n"


def build(limit: int | None = None) -> str:
    cases = load()
    if limit:
        keep = {c["pair"] for c in cases if c["pair"]}
        keep = set(sorted(keep)[:limit])
        cases = [c for c in cases if c["pair"] in keep] + [c for c in cases if c["role"] == "decoy"][:limit]
    header = ("# Generated by evals/eval_integrity/build_kaggle_task.py. Do not edit by hand.\n"
              "# Syntax reference: https://github.com/Kaggle/kaggle-benchmarks\n"
              "# No `from __future__ import annotations`: the SDK reads return types at runtime.\n"
              "import json\n\n")
    body = "\n\n".join(module_source(m) for m in MODULES)
    return header + body + TASK.format(sha=fingerprint(), cases=json.dumps(cases), name=TASK_NAME)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--limit", type=int, default=None, help="only this many pairs and decoys (for a smoke run)")
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args(argv)
    args.out.write_text(build(args.limit), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
